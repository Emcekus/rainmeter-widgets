#!/usr/bin/env python3
"""Build the Katana Desktop Rainmeter suite: Clock, CPU, Memory, Battery, Text.

    python build.py [--wear 0.12] [--clock-cell 4] [--cell 2] [--out dist]

--clock-cell / --cell are screen pixels per design pixel (the design's resize handle).
Needs Node + Playwright (font rasterization) and Pillow + numpy.
Produces dist/KatanaDesktop_<version>.rmskin.
"""
import argparse, json, os, shutil, struct, subprocess, zipfile
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
VERSION = '2.0'
PAL = ['#4a6e42', '#4c7044', '#4e7346', '#46693f', '#50754a']   # bright cells
PAL_D = ['#1d301a', '#1f331c', '#21361e']                       # dim cells (unlit segments)
PALETTE = [0, 0, 0] + [int(c[i:i + 2], 16) for c in PAL + PAL_D for i in (1, 3, 5)]


# ---------------------------------------------------------------- pixels
def cells_of(p):
    return np.frombuffer(p['cells'].encode(), dtype=np.uint8).reshape(p['h'], p['w']) - ord('0')


def save_png(cells, cell, path):
    """Same cell shapes as the design: cell<=2 -> thin vertical strips, else v6 squares."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    h, w = cells.shape
    img = np.zeros((max(h, 1) * cell, max(w, 1) * cell), dtype=np.uint8)
    for y, x in zip(*np.nonzero(cells)):
        if cell <= 2:
            cw, ch = max(cell - 1, 1), cell
        else:
            cw, ch = cell - 1, (cell if y % 2 else cell - 1)
        img[y * cell:y * cell + ch, x * cell:x * cell + cw] = cells[y, x]
    im = Image.fromarray(img, 'P')
    im.putpalette(PALETTE)
    im.save(path, optimize=True, transparency=0)


def bbox(c):
    ys, xs = np.nonzero(c)
    return ys.min(), ys.max(), xs.min(), xs.max()


def static(p, cell, path):
    """Crop a piece to its ink and save. Returns (X, Y) in screen px within the widget."""
    c = cells_of(p)
    y0, y1, x0, x1 = bbox(c)
    save_png(c[y0:y1 + 1, x0:x1 + 1], cell, path)
    return (p['x'] + x0) * cell, (p['y'] + y0) * cell


def fixed(p, cell, path):
    save_png(cells_of(p), cell, path)
    return p['x'] * cell, p['y'] * cell


def glyph_set(gs, cell, img_dir, lua_path):
    """Save a glyph set (shared top row, right-trimmed) plus its Lua metrics table. Returns top row."""
    pieces = {int(k): cells_of(v) for k, v in gs['glyphs'].items()}
    rows = np.zeros(next(iter(pieces.values())).shape[0], bool)
    for c in pieces.values():
        rows |= c.any(axis=1)
        if c[:, 0].any():
            print('warning: glyph ink touches left edge in', img_dir)
    r = np.nonzero(rows)[0]
    r0, r1 = r[0], r[-1]
    for code, c in pieces.items():
        ink = np.nonzero(c.any(axis=0))[0]
        right = ink[-1] + 1 if ink.size else 1
        save_png(c[r0:r1 + 1, :right], cell, os.path.join(img_dir, f'{code}.png'))
    adv = ', '.join(f'[{k}]={v:.4f}' for k, v in sorted(((int(k), v) for k, v in gs['adv'].items())))
    kern = ', '.join(f'[{k}]={v}' for k, v in sorted(((int(k), v) for k, v in gs['kern'].items())))
    os.makedirs(os.path.dirname(lua_path), exist_ok=True)
    with open(lua_path, 'w', newline='\r\n') as f:
        f.write(f'-- Generated by build.py\nreturn {{ pad={gs["pad"]}, top={int(r0)},\n'
                f'  adv={{ {adv} }},\n  kern={{ {kern} }} }}\n')
    return int(r0)


# ---------------------------------------------------------------- ini text
def head(name, info, cell, extra_rainmeter='', extra_vars=''):
    return f"""[Rainmeter]
Update=1000
DynamicWindowSize=1
AccurateText=1
{extra_rainmeter}
[Metadata]
Name=Katana Desktop - {name}
Author=Mykolas Mickus
Information={info} Drag anywhere on the widget to move it.
Version={VERSION}
License=Personal use. Font: Reggae One, SIL Open Font License 1.1

[Variables]
Cell={cell}
{extra_vars}
"""


def hit(w, h, dynamic=False):
    # Alpha 1 is invisible but makes the whole box grabbable (fully transparent pixels ignore the mouse).
    return f"""[MeterHit]
Meter=Image
SolidColor=0,0,0,1
X=0
Y=0
W={w}
H={h}
{'DynamicVariables=1' if dynamic else ''}
"""


def img(name, image, x, y, hidden=False, dynamic=False, measure=None):
    s = f'[{name}]\nMeter=Image\n'
    if measure:
        s += f'MeasureName={measure}\n'
    if image:
        s += f'ImageName={image}\n'
    s += f'X={x}\nY={y}\n'
    if hidden:
        s += 'Hidden=1\n'
    if dynamic:
        s += 'DynamicVariables=1\n'
    return s + '\n'


def slots(prefix, n, y):
    return ''.join(img(f'{prefix}{i}', None, 0, y, hidden=True, dynamic=True) for i in range(1, n + 1))


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', newline='\r\n') as f:
        f.write(text)


# ---------------------------------------------------------------- build
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--wear', type=float, default=0.12)
    ap.add_argument('--clock-cell', type=int, default=4)
    ap.add_argument('--cell', type=int, default=2, help='cell size for CPU, Memory, Battery, Text')
    ap.add_argument('--out', default=os.path.join(HERE, 'dist'))
    a = ap.parse_args()
    CC, C = a.clock_cell, a.cell

    os.makedirs(a.out, exist_ok=True)
    cj = os.path.join(a.out, 'cells.json')
    subprocess.run(['node', os.path.join(HERE, 'rasterize.js'), cj, str(a.wear)], check=True)
    d = json.load(open(cj))

    root = os.path.join(a.out, 'Skins', 'KatanaDesktop')
    shutil.rmtree(os.path.join(a.out, 'Skins'), ignore_errors=True)
    shutil.rmtree(os.path.join(a.out, 'Layouts'), ignore_errors=True)
    res = os.path.join(root, '@Resources')
    imgs = os.path.join(res, 'Images')
    scripts = os.path.join(res, 'Scripts')
    shutil.copytree(os.path.join(HERE, 'skin', 'Scripts'), scripts)
    sizes = {}

    # ----- Clock
    ck = d['clock']
    times = {k: cells_of(v) for k, v in ck['time'].items()}
    rows = np.zeros(58, bool)
    for g in times.values():
        rows |= g.any(axis=1)
    t0, t1 = np.nonzero(rows)[0][[0, -1]]
    tcol = max(np.nonzero(g.any(axis=0))[0][-1] for g in times.values())
    for k, g in times.items():
        save_png(g[t0:t1 + 1, :tcol + 1], CC, os.path.join(imgs, 'Clock', 'Time', k + '.png'))
    pad = ck['meta']['pad']
    parts = [(cat, folder, {k: (cells_of(v), v['adv']) for k, v in ck[cat].items()})
             for cat, folder in (('weekday', 'Weekday'), ('day', 'Day'), ('month', 'Month'))]
    drows = np.zeros(26, bool)
    for _, _, ps in parts:
        for g, _ in ps.values():
            drows |= g.any(axis=1)
    d0, d1 = np.nonzero(drows)[0][[0, -1]]
    for cat, folder, ps in parts:
        for k, (g, adv) in ps.items():
            w = pad + round(adv) + pad
            if np.nonzero(g.any(axis=0))[0][-1] >= w:
                print('warning: clock date ink clipped', cat, k)
            save_png(g[d0:d1 + 1, :w], CC, os.path.join(imgs, 'Clock', 'Date', folder, k + '.png'))
    gap = round(ck['meta']['space']) - 2 * pad
    date_y = int(56 + d0 - t0)
    date_x = ck['meta']['dateX'] - pad
    clock_w, clock_h = int(tcol + 1) * CC, int(date_y + d1 - d0 + 1) * CC
    sizes['Clock'] = (clock_w, clock_h)
    write(os.path.join(root, 'Clock', 'Clock.ini'), head('Clock', '24-hour clock with date.', CC) + f"""
[MeasureTime]
Measure=Time
Format=%H%M

[MeasureWeekday]
Measure=Time
Format=%w

[MeasureDay]
Measure=Time
Format=%d

[MeasureMonth]
Measure=Time
Format=%m

{hit(clock_w, clock_h)}
{img('MeterTime', r'#@#Images\Clock\Time\%1.png', 0, 0, measure='MeasureTime')}\
{img('MeterWeekday', r'#@#Images\Clock\Date\Weekday\%1.png', date_x * CC, date_y * CC, measure='MeasureWeekday')}\
{img('MeterDay', r'#@#Images\Clock\Date\Day\%1.png', f'({gap * CC})R', '0r', measure='MeasureDay')}\
{img('MeterMonth', r'#@#Images\Clock\Date\Month\%1.png', f'({gap * CC})R', '0r', measure='MeasureMonth')}""")

    # ----- CPU
    cpu = d['cpu']
    sx, sy = static(cpu['static'], C, os.path.join(imgs, 'CPU', 'static.png'))
    for k, p in cpu['bar'].items():
        fixed(p, C, os.path.join(imgs, 'CPU', 'bar', k + '.png'))
    top = glyph_set(cpu['big'], C, os.path.join(imgs, 'CPU', 'big'), os.path.join(scripts, 'glyphs_cpu.lua'))
    bars = ''.join(img(f'MeterBar{i + 1}', rf'#@#Images\CPU\bar\{i}_1.png', (i * 6 + 1) * C, 52 * C, dynamic=True) for i in range(18))
    sizes['CPU'] = (112 * C, 72 * C)
    write(os.path.join(root, 'CPU', 'CPU.ini'), head('CPU', 'Total CPU load with a short history.', C) + f"""
[MeasureCPU]
Measure=CPU
Processor=0

[MeasureScript]
Measure=Script
ScriptFile=#@#Scripts\\cpu.lua

{hit(112 * C, 72 * C)}
{img('MeterStatic', r'#@#Images\CPU\static.png', sx, sy)}{bars}{slots('MeterNum', 4, top * C)}""")

    # ----- Memory
    mem = d['mem']
    sx, sy = static(mem['static'], C, os.path.join(imgs, 'Memory', 'static.png'))
    for k, p in mem['seg'].items():
        fixed(p, C, os.path.join(imgs, 'Memory', 'seg', k + '.png'))
    top = glyph_set(mem['big'], C, os.path.join(imgs, 'Memory', 'big'), os.path.join(scripts, 'glyphs_mem.lua'))
    utop = glyph_set(mem['unit'], C, os.path.join(imgs, 'Memory', 'unit'), os.path.join(scripts, 'glyphs_mem_unit.lua'))
    segs = ''.join(img(f'MeterSeg{i + 1}', rf'#@#Images\Memory\seg\{i}_0.png', (1 + i * 9) * C, 58 * C, dynamic=True) for i in range(12))
    sizes['Memory'] = (112 * C, 72 * C)
    write(os.path.join(root, 'Memory', 'Memory.ini'), head('Memory', 'Used RAM in GB and as a share of total.', C) + f"""
[MeasureMemUsed]
Measure=PhysicalMemory

[MeasureMemTotal]
Measure=PhysicalMemory
Total=1

[MeasureScript]
Measure=Script
ScriptFile=#@#Scripts\\mem.lua

{hit(112 * C, 72 * C)}
{img('MeterStatic', r'#@#Images\Memory\static.png', sx, sy)}{segs}{slots('MeterNum', 5, top * C)}{slots('MeterUnit', 2, utop * C)}""")

    # ----- Battery
    bat = d['bat']
    sx, sy = static(bat['static'], C, os.path.join(imgs, 'Battery', 'static.png'))
    cx, cy = static(bat['chg'], C, os.path.join(imgs, 'Battery', 'chg.png'))
    for k, p in bat['gauge'].items():
        gx, gy = fixed(p, C, os.path.join(imgs, 'Battery', 'gauge', k + '.png'))
    top = glyph_set(bat['big'], C, os.path.join(imgs, 'Battery', 'big'), os.path.join(scripts, 'glyphs_bat.lua'))
    sizes['Battery'] = (96 * C, 72 * C)
    write(os.path.join(root, 'Battery', 'Battery.ini'), head('Battery', 'Battery level; CHG shows while plugged in.', C) + f"""
[MeasureBattery]
Measure=Plugin
Plugin=PowerPlugin
PowerState=PERCENT

[MeasureACLine]
Measure=Plugin
Plugin=PowerPlugin
PowerState=ACLINE

[MeasureScript]
Measure=Script
ScriptFile=#@#Scripts\\bat.lua

{hit(96 * C, 72 * C)}
{img('MeterStatic', r'#@#Images\Battery\static.png', sx, sy)}\
{img('MeterCharging', r'#@#Images\Battery\chg.png', cx, cy, hidden=True)}\
{img('MeterGauge', r'#@#Images\Battery\gauge\0.png', gx, gy, dynamic=True)}{slots('MeterNum', 4, top * C)}""")

    # ----- Text
    top = glyph_set(d['text']['g'], C, os.path.join(imgs, 'Text', 'glyph'), os.path.join(scripts, 'glyphs_text.lua'))
    write(os.path.join(res, 'Text.inc'), '[Variables]\nText=STAY SHARP\n')
    min_w = 240
    sizes['Text'] = (min_w, 30 * C)
    write(os.path.join(root, 'Text', 'Text.ini'), head(
        'Text', 'Your own line of text (right-click > Edit text).', C,
        extra_rainmeter='ContextTitle=Edit text\nContextAction=[!CommandMeasure MeasureInput "ExecuteBatch 1"]\n',
        extra_vars=f'MinWidth={min_w}\n@Include=#@#Text.inc\n') + f"""
[MeasureScript]
Measure=Script
ScriptFile=#@#Scripts\\text.lua

[MeasureInput]
Measure=Plugin
Plugin=InputText
X=0
Y=0
W={min_w}
H=30
SolidColor=5,19,5,255
FontColor=182,228,148,255
FontFace=Segoe UI
FontSize=12
InputLimit=24
DefaultValue=#Text#
Command1=[!WriteKeyValue Variables Text "$UserInput$" "#@#Text.inc"][!Refresh]

{hit(min_w, 30 * C, dynamic=True)}
{slots('MeterChar', 24, top * C)}""")

    # ----- Layout: positions follow the design's arrangement
    x0, y0, gapx = 56, 48, 32
    row2 = y0 + clock_h + 40
    pos = {'Clock': (x0, y0),
           'CPU': (x0, row2),
           'Memory': (x0 + sizes['CPU'][0] + gapx, row2),
           'Battery': (x0 + sizes['CPU'][0] + sizes['Memory'][0] + 2 * gapx, row2),
           'Text': (x0, row2 + sizes['CPU'][1] + 40)}
    layout = '[Rainmeter]\n\n' + ''.join(f"""[KatanaDesktop\\{n}]
Active=1
WindowX={x}
WindowY={y}
AlwaysOnTop=-2
Draggable=1
ClickThrough=0
SnapEdges=0
KeepOnScreen=1
SavePosition=1

""" for n, (x, y) in pos.items())
    write(os.path.join(a.out, 'Layouts', 'KatanaDesktop', 'Rainmeter.ini'), layout)

    # ----- .rmskin = zip + RMSKIN.ini + 16-byte footer
    rmskin_ini = f"""[rmskin]
Name=Katana Desktop
Author=Mykolas Mickus
Version={VERSION}
MinimumRainmeter=4.5.0
MinimumWindows=10.0
LoadType=Layout
Load=KatanaDesktop
VariableFiles=KatanaDesktop\\@Resources\\Text.inc
""".replace('\n', '\r\n')
    pkg = os.path.join(a.out, f'KatanaDesktop_{VERSION}.rmskin')
    with zipfile.ZipFile(pkg, 'w', zipfile.ZIP_DEFLATED) as z:
        z.writestr('RMSKIN.ini', rmskin_ini)
        for top_dir in ('Skins', 'Layouts'):
            for r, _, files in os.walk(os.path.join(a.out, top_dir)):
                for fn in sorted(files):
                    p = os.path.join(r, fn)
                    z.write(p, os.path.relpath(p, a.out).replace(os.sep, '/'))
    size = os.path.getsize(pkg)
    with open(pkg, 'ab') as f:
        f.write(struct.pack('<q', size) + b'\x00' + b'RMSKIN\x00')

    json.dump({'positions': pos, 'sizes': sizes, 'clockCell': CC, 'cell': C},
              open(os.path.join(a.out, 'layout.json'), 'w'), indent=1)
    print('built', pkg, f'({os.path.getsize(pkg) / 1e6:.2f} MB)')


if __name__ == '__main__':
    main()
